const ENTRY_LINES = {
  rust: /^\[crate\] (\S+) (\S+) https:\/\/crates\.io\/crates\/\1\/\2$/,
  npm: /^\[npm\] (\S+) (\S+) (.+)$/,
};
const NPM_FIELDS = ['name', 'version', 'identifier', 'text'];
const VITE_CORE_LICENSE_START = 'MIT License';
const VITE_BUNDLED_LICENSES_HEADING = '# Licenses of bundled dependencies';
const LINE_BREAK = /\r?\n/;

export class NoticesError extends Error {
  constructor(message, options) {
    super(message, options);
    this.name = 'NoticesError';
  }
}

export function compareCodePoint(a, b) {
  if (a < b) return -1;
  if (a > b) return 1;
  return 0;
}

export function packageKey(name, version) {
  return `${name}@${version}`;
}

function requireEntry(map, id, kind) {
  const entry = map.get(id);
  if (entry === undefined) throw new NoticesError(`cargo metadata has no ${kind} ${id}`);
  return entry;
}

function rootId(metadata) {
  const id = metadata.resolve?.root;
  if (!id) throw new NoticesError('cargo metadata has no root package');
  return id;
}

function packagesById(metadata) {
  return new Map(metadata.packages.map((pkg) => [pkg.id, pkg]));
}

function isNormalDependency(dep) {
  return dep.dep_kinds.some((depKind) => depKind.kind === null);
}

export function rootCrateKey(metadata) {
  const root = requireEntry(packagesById(metadata), rootId(metadata), 'package');
  return packageKey(root.name, root.version);
}

export function normalClosure(metadata) {
  const packages = packagesById(metadata);
  const nodes = new Map(metadata.resolve.nodes.map((node) => [node.id, node]));
  const start = rootId(metadata);
  const seen = new Set([start]);
  const pending = [start];
  const closure = new Map();
  while (pending.length > 0) {
    for (const dep of requireEntry(nodes, pending.pop(), 'resolve node').deps) {
      if (seen.has(dep.pkg) || !isNormalDependency(dep)) continue;
      seen.add(dep.pkg);
      pending.push(dep.pkg);
      const { name, version, manifest_path } = requireEntry(packages, dep.pkg, 'package');
      closure.set(packageKey(name, version), { name, version, dir: dirname(manifest_path) });
    }
  }
  return closure;
}

export function parseCargoTree(text) {
  const keys = new Set();
  for (const line of text.split(LINE_BREAK)) {
    const [name, version] = line.trim().split(/\s+/);
    if (!name) continue;
    if (!version?.startsWith('v')) throw new NoticesError(`unexpected cargo tree line: ${line}`);
    keys.add(packageKey(name, version.slice(1)));
  }
  return keys;
}

export function parseNoticeEntries(text) {
  const entries = { rust: new Set(), npm: new Set() };
  let section = null;
  for (const line of text.split(LINE_BREAK)) {
    if (section === null && line === RUST_SECTION) {
      section = 'rust';
    } else if (section === 'rust' && line === NPM_SECTION) {
      section = 'npm';
    } else if (section !== null) {
      const match = ENTRY_LINES[section].exec(line);
      if (match) entries[section].add(packageKey(match[1], match[2]));
    }
  }
  return entries;
}

export function diffEntries({ required, allowed, actual }) {
  return {
    missing: [...required.keys()].filter((key) => !actual.has(key)).sort(compareCodePoint),
    extra: [...actual.keys()].filter((key) => !allowed.has(key)).sort(compareCodePoint),
  };
}

function npmEntryLabel(entry, index) {
  const name = typeof entry?.name === 'string' && entry.name !== '' ? entry.name : '?';
  const version = typeof entry?.version === 'string' && entry.version !== '' ? entry.version : '?';
  return `#${index} ${packageKey(name, version)}`;
}

function npmEntryErrors(entry, index) {
  const label = npmEntryLabel(entry, index);
  const errors = NPM_FIELDS.filter(
    (field) => typeof entry?.[field] !== 'string' || entry[field].trim() === '',
  ).map((field) => `npm entry ${label} has no ${field}`);
  if (/\s/.test(entry?.name ?? '') || /\s/.test(entry?.version ?? '')) {
    errors.push(`npm entry ${label} has whitespace in its name or version`);
  }
  if (/[\r\n]/.test(entry?.identifier ?? '')) {
    errors.push(`npm entry ${label} has a multi-line license identifier`);
  }
  if (typeof entry?.text === 'string' && entry.text.trimStart().startsWith('SPDXVersion:')) {
    errors.push(`npm entry ${label} uses an SPDX document instead of a license text`);
  }
  return errors;
}

export function validateNpmEntries(entries) {
  if (!Array.isArray(entries)) return ['licenses.json is not an array'];
  return entries.flatMap(npmEntryErrors);
}

export function usesModulePreloadPolyfill(jsSources) {
  return jsSources.some((source) => source.includes('relList'));
}

export function usesRolldownRuntime(jsSources) {
  return jsSources.some((source) => source.includes('__commonJS'));
}

export function viteCoreLicense(licenseMd) {
  const lines = licenseMd.split(LINE_BREAK);
  const start = lines.indexOf(VITE_CORE_LICENSE_START);
  if (start === -1) {
    throw new NoticesError(`vite LICENSE.md has no "${VITE_CORE_LICENSE_START}" line`);
  }
  const end = lines.indexOf(VITE_BUNDLED_LICENSES_HEADING, start + 1);
  if (end === -1) {
    throw new NoticesError(
      `vite LICENSE.md has no "${VITE_BUNDLED_LICENSES_HEADING}" line after the core license`,
    );
  }
  return lines.slice(start, end).join('\n').trim();
}

function compareNpmEntries(a, b) {
  return (
    compareCodePoint(a.name, b.name) ||
    compareCodePoint(a.version, b.version) ||
    compareCodePoint(a.identifier, b.identifier) ||
    compareCodePoint(a.text, b.text)
  );
}

function renderNpmEntry({ name, version, identifier, text }) {
  return ['', SEPARATOR, `[npm] ${name} ${version} ${identifier}`, '', text.trimEnd()].join('\n');
}

export function renderNpmSection(entries) {
  return [NPM_SECTION, ...[...entries].sort(compareNpmEntries).map(renderNpmEntry)].join('\n');
}

export function packageNames(keys) {
  return new Set([...keys].map((key) => key.slice(0, key.lastIndexOf('@'))));
}

export function missingSupplementCrates(supplement, rustListedNames) {
  return supplement.crates.filter((name) => !rustListedNames.has(name)).sort(compareCodePoint);
}

function supplementCommit(supplement) {
  const match = /\/blob\/([0-9a-f]{40})(?=\/)/.exec(supplement.source);
  if (!match) throw new NoticesError(`supplement source has no commit: ${supplement.source}`);
  return match[1];
}

export function supplementLine(supplement) {
  return `[supplement] ${[...supplement.crates].sort(compareCodePoint).join(' ')}`;
}

export function missingSupplementBlocks(supplements, noticesText) {
  const lines = new Set(noticesText.split(LINE_BREAK));
  return supplements.filter((supplement) => !lines.has(supplementLine(supplement)));
}

export function renderSupplement(supplement, text) {
  return [
    SEPARATOR,
    `${supplement.heading}, supplementary text`,
    '',
    supplementLine(supplement),
    '',
    'The released versions of these crates ship only the upstream LICENSE.md statement',
    `listed above under "${supplement.heading}". Upstream added the following ${supplement.license} license`,
    `text to its repository in commit ${supplementCommit(supplement)}:`,
    supplement.source,
    '',
    text.trimEnd(),
  ].join('\n');
}

export function renderNotices({ header, rust, supplements = [], npmEntries }) {
  if (rust.split(LINE_BREAK, 1)[0] !== RUST_SECTION) {
    throw new NoticesError(
      `cargo-about output must start with the line "${RUST_SECTION}"; check src-tauri/about.hbs`,
    );
  }
  const blocks = [
    header.trimEnd(),
    rust.trimEnd(),
    ...supplements.map(({ supplement, text }) => renderSupplement(supplement, text)),
    renderNpmSection(npmEntries),
  ];
  return `${blocks.join('\n\n')}\n`;
}

export function isNoticeFileName(name) {
  return /^notice/i.test(name);
}
